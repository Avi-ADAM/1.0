/** Words a member may type instead of pressing a button, in any bot language. */
export const CANCEL_WORDS = ['ביטול', 'בטל', 'cancel', 'stop', 'quit', 'إلغاء', 'الغاء', 'отмена', 'отменить', 'cancelar'];
const TODAY_WORDS = ['היום', 'today', 'اليوم', 'сегодня', 'hoy'];
const YESTERDAY_WORDS = ['אתמול', 'yesterday', 'أمس', 'امس', 'вчера', 'ayer'];
/** "Nothing" for an optional field, beside the universal "-". */
export const NONE_WORDS = ['none', 'אין', 'لا يوجد', 'нет', 'ninguno', 'ninguna'];

/** @param {string} text */
export function isCancelWord(text) {
    return CANCEL_WORDS.includes(String(text ?? '').trim().toLowerCase());
}

/** @param {string} text @returns {'today'|'yesterday'|null} */
export function relativeDayWord(text) {
    const lower = String(text ?? '').trim().toLowerCase();
    if (TODAY_WORDS.includes(lower)) return 'today';
    if (YESTERDAY_WORDS.includes(lower)) return 'yesterday';
    return null;
}

/** @param {unknown} code */
function supported(code) {
    if (typeof code !== 'string' || !code) return null;
    let base = code.toLowerCase().split(/[-_]/)[0];
    if (base === 'iw') base = 'he'; // Telegram clients still send the old Hebrew code
    return BOT_LANGS.includes(/** @type {any} */ (base)) ? base : null;
}

/**
 * Which language the bot answers in. The account's own choice wins; a chat with
 * no linked account (or an account that never chose) gets the language the
 * person's Telegram app reports; Hebrew only when neither says anything.
 *
 * @param {unknown} accountLang  `User.lang` of the linked account, if any
 * @param {unknown} telegramLang `ctx.from.language_code`
 */
export function resolveBotLang(accountLang, telegramLang) {
    return supported(accountLang) ?? supported(telegramLang) ?? 'he';
}

/**
 * @param {string} key
 * @param {string} [lang]
 * @param {Record<string, string|number>} [replacements]
 */
export function botText(key, lang = 'he', replacements = {}) {
    let text = BOT_TEXTS[lang]?.[key] ?? BOT_TEXTS.en[key] ?? BOT_TEXTS.he[key] ?? key;
    for (const placeholder in replacements) {
        text = text.split(`{{${placeholder}}}`).join(String(replacements[placeholder]));
    }
    return text;
}

/** @param {string} lang */
export function botDateLocale(lang) {
    return DATE_LOCALES[lang] ?? DATE_LOCALES.en;
}
